// scripts/build-tokutei-bank.mjs — bundle the exported Indonesian N5/N4 question JSON into a
// single browser-loadable data file for the Specified Skilled Worker (特定技能) practice page.
// Keeps the raw question HTML (ruby/underline render natively in the browser). Run after
// export-drill-pack.mjs N5 id / N4 id. Output: data/tokutei-bank.js (window.NH_TOKUTEI).
import fs from "fs";

function load(level) {
  const p = new URL(`./data/drill-${level}-id.json`, import.meta.url);
  return JSON.parse(fs.readFileSync(p, "utf8")).items;
}

// light dedupe: collapse near-identical variants (same bare stem + answer kanji-core)
function key(it) {
  let s = it.question
    .replace(/<rt>.*?<\/rt>/g, "")
    .replace(/<[^>]+>/g, "")
    .replace(/（[^）]*）/g, "")
    .replace(/[。、，．！？\s]/g, "")
    .replace(/(ます|ました|ません|です)$/u, "");
  const ans = String(it.correct).replace(/[぀-ゟ]+$/u, "") || String(it.correct);
  return s + "|" + ans;
}

function clean(items) {
  const seen = new Set();
  const out = [];
  for (const it of items) {
    const k = key(it);
    if (seen.has(k)) continue;
    seen.add(k);
    out.push({
      q: it.question,
      instr: (it.reading || "Pilih jawaban yang benar.").trim(),
      correct: it.correct,
      distractors: it.distractors,
      explanation: (it.explanation || "").trim(),
    });
  }
  return out;
}

const bank = { n5: clean(load("N5")), n4: clean(load("N4")) };
const out = new URL("./../data/tokutei-bank.js", import.meta.url);
fs.writeFileSync(
  out,
  "/* Auto-generated by scripts/build-tokutei-bank.mjs — Indonesian JLPT N5/N4 practice pool\n" +
  "   for the 特定技能 (Specified Skilled Worker) prep page. Do not edit by hand. */\n" +
  "window.NH_TOKUTEI = " + JSON.stringify(bank) + ";\n",
  "utf8"
);
console.log(`wrote data/tokutei-bank.js  (N5 ${bank.n5.length}, N4 ${bank.n4.length})`);
